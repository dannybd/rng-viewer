function get_blaseball_hour_info(hour) {
  hour = parseFloat(hour);
  const date = new Date((BLASEBALL_EPOCH + hour * 3600) * 1000);
  const flatHour = parseInt(Math.floor(hour), 10);
  const {season, day} = BLASEBALL_HOURS_TO_GAME_DAYS[flatHour] ?? {season: null, day: null};
  return {
    hour,
    date,
    season,
    day,
  };
}
